#!/usr/bin/env python3
"""
Make apps/md/core/cpus/M68K/m68ki_jump_small.h from m68ki_instruction_jump_table.h.

The 68000's jump table is 65 536 function pointers: 256 KB, and each one is a
relocation the loader has to hold in memory whole while it places the image -
another 256 KB.  The CYD has neither.  There are only a couple of thousand
distinct handlers, so the small build keeps a 16-bit index per opcode (128 KB,
no relocations, read out of flash a word at a time) and one short array of the
handlers themselves.

An instruction's cycle count is a property of its handler (1700 handlers, 1701
distinct handler/cycle pairs), so each entry of that array carries the cycles
too: the 64 KB per-opcode cycle table - another flash read per instruction - is
gone, and the count arrives in the same cache line as the pointer.

    python tools/gen_md_jump_small.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
DIR = os.path.join(HERE, '..', 'apps', 'md', 'core', 'cpus', 'M68K')
src = open(os.path.join(DIR, 'm68ki_instruction_jump_table.h'), encoding='latin-1').read()
body = src[src.index('{') + 1:src.rindex('}')]
names = re.findall(r'm68k_op_[A-Za-z0-9_]+', body)
# The table stops at 0xEFBF: line F (0xF000 up) is not in it, and Musashi's own
# table entry for it, m68k_op_1111, is not compiled here: m68k_op_illegal stands in.  Without the tail an opcode there would
# index past the end, as it already did through the original table.
assert len(names) <= 0x10000, len(names)
names += ['m68k_op_illegal'] * (0x10000 - len(names))

csrc = open(os.path.join(DIR, 'm68ki_cycles.h'), encoding='latin-1').read()
cbody = csrc[csrc.index('{') + 1:csrc.rindex('}')]
cycles = [eval(x) for x in re.findall(r'\d+\*\d+', cbody)]
assert len(cycles) <= 0x10000 and max(cycles) < 256, (len(cycles), max(cycles))
cycles += [0] * (0x10000 - len(cycles))

order = []
index = {}
for pair in zip(names, cycles):
    if pair not in index:
        index[pair] = len(order)
        order.append(pair)
assert len(order) < 0x10000

out = []
out.append('/* Generated by tools/gen_md_jump_small.py - do not edit. */')
out.append('/* %d distinct handler/cycle pairs for 65536 opcodes. */' % len(order))
out.append('typedef struct { void (*fn)(void); unsigned int cyc; } md_op_t;')
out.append('__attribute__((used, aligned(8), section(".hot_rodata")))')
out.append('static const md_op_t md_ops[%d] =\n{' % len(order))
for i in range(0, len(order), 3):
    out.append('  ' + ' '.join('{%s, %d},' % p for p in order[i:i + 3]))
out.append('};')
out.append('__attribute__((used, aligned(4), section(".hot_rodata")))')
out.append('static const unsigned short md_op_index[0x10000] =\n{')
idx = [index[p] for p in zip(names, cycles)]
for i in range(0, 0x10000, 16):
    out.append('  ' + ', '.join(str(v) for v in idx[i:i + 16]) + ',')
out.append('};')
out.append('/* The index is in flash, which the ESP32 reads only a word at a time. */')
out.append('#define MD_OP(op) (&md_ops[(((const unsigned int *)(const void *)md_op_index)'
           '[(op) >> 1] >> (((op) & 1) << 4)) & 0xFFFF])')
open(os.path.join(DIR, 'm68ki_jump_small.h'), 'w', encoding='latin-1', newline='\n').write('\n'.join(out) + '\n')
print('handler/cycle pairs:', len(order))
