#!/usr/bin/env python3
"""Which 68000 handlers go in MD-NO-PSRAM's (the CYD's) hot part: the ones a game actually runs.

    python tools/gen_md_hot.py HIST SIZES BUDGET > apps/md/core/cpus/M68K/md_hot.h

HIST is a histogram of handler indexes from the host harness (MD_HOST_COUNT,
MD_HIST_OUT: "index count" per line, over a whole session of a game); SIZES is
`nm -S` of an MD-NO-PSRAM build ("size name" per line) so the budget is in the CYD's
own bytes.  Handlers are taken most-executed first until BUDGET bytes are
spent.  What is not taken stays in flash and still works - only slower.
"""
import re
import sys


def main():
    hist_path, sizes_path, budget = sys.argv[1], sys.argv[2], int(sys.argv[3])
    src = open('apps/md/core/cpus/M68K/m68ki_jump_small.h', encoding='latin-1').read()
    body = src[src.index('md_ops[1701] =') + 15:src.index('};')]
    names = re.findall(r'\{(\w+),\s*\d+\}', body)
    size = {}
    for line in open(sizes_path):
        p = line.split()
        if len(p) == 2:
            size[p[1]] = int(p[0], 16)
    hist = [tuple(map(int, l.split())) for l in open(hist_path) if l.strip()]
    hist.sort(key=lambda kv: -kv[1])
    total = sum(c for _, c in hist)
    chosen, spent, covered = [], 0, 0
    for k, c in hist:
        n = names[k]
        if n in chosen or n == 'm68k_op_illegal':
            continue
        b = size.get(n, 64)
        if spent + b > budget:
            continue
        chosen.append(n)
        spent += b
        covered += c
    print('/* Generated by tools/gen_md_hot.py - do not edit.')
    print(' * %d handlers, %d bytes, %.2f%% of the instructions of the session '
          'measured. */' % (len(chosen), spent, 100.0 * covered / total))
    for n in sorted(chosen):
        print('static void %s(void) MD_HOT;' % n)


if __name__ == '__main__':
    main()
