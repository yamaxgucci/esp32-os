#!/usr/bin/env python3
"""Generate ArgonOS YM2612 tl/sin/LFO tables (no libm at runtime).

Mirrors init_tables() in apps/md/core/sound/ym2612.c with GW_TARGET=1.
"""
from __future__ import annotations

import math
import pathlib

ENV_BITS = 10
ENV_LEN = 1 << ENV_BITS
ENV_STEP = 128.0 / ENV_LEN
SIN_BITS = 10
SIN_LEN = 1 << SIN_BITS
TL_RES_LEN = 256
TL_TAB_LEN = 13 * 2 * TL_RES_LEN
M_PI = math.pi

# Copied from ym2612.c (lfo_pm_output).
