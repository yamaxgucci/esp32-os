static void key_of(uint8_t key[32], uint8_t first)
{
    for (int i = 0; i < 32; i++) {
        key[i] = (uint8_t)(first + i);
    }
}

static void test_licence_reads_back(void)
{
    ag_axe_header_t h;
    memcpy(&h, k_licensed, sizeof(h));
    AG_CHECK((h.flags & AG_AXE_LICENSED) != 0u);
    AG_CHECK_INT((int)h.abi_minor, 72);

    ag_licence_block_t block;
    AG_CHECK_INT(ag_licence_find(k_licensed, sizeof(k_licensed), &block), AG_OK);

    uint8_t key[32];
    key_of(key, 0);
    ag_licence_t lic;
    AG_CHECK_INT(ag_licence_begin(&lic, &h, &block, key), AG_OK);

    /* All of it at once: the parts come back, everything else is untouched. */
    uint8_t file[sizeof(k_licensed)];
    memcpy(file, k_licensed, sizeof(file));
    ag_licence_apply(&lic, 0, file, sizeof(file));
    AG_CHECK(memcmp(file + 176, k_plain + 176, sizeof(k_plain) - 176) == 0);
    AG_CHECK(memcmp(file, k_licensed, 176) == 0);

    /* In odd pieces and out of order, as the loader reads it. */
    memcpy(file, k_licensed, sizeof(file));
    static const size_t cuts[][2] = {{230, 12}, {0, 3}, {3, 190}, {193, 37},
                                     {242, 40}};
    for (size_t i = 0; i < sizeof(cuts) / sizeof(cuts[0]); i++) {
        ag_licence_apply(&lic, cuts[i][0], file + cuts[i][0], cuts[i][1]);
    }
    AG_CHECK(memcmp(file + 176, k_plain + 176, sizeof(k_plain) - 176) == 0);
}

static void test_licence_refuses_another_key(void)
{
    ag_axe_header_t h;
    memcpy(&h, k_licensed, sizeof(h));
    ag_licence_block_t block;
    AG_CHECK_INT(ag_licence_find(k_licensed, sizeof(k_licensed), &block), AG_OK);
    ag_licence_t lic;
    uint8_t      key[32];

    key_of(key, 1);
    AG_CHECK_INT(ag_licence_begin(&lic, &h, &block, key), -AG_EPERM);

    /* The right id copied into the block is not enough: the check is the
     * key's, and a key that does not make it does not open the file. */
    key_of(key, 0);
    block.check[0] ^= 1u;
    AG_CHECK_INT(ag_licence_begin(&lic, &h, &block, key), -AG_EPERM);

    /* A program renamed in its header is not the program that was bought. */
    block.check[0] ^= 1u;
    h.name[0] = 'X';
    AG_CHECK_INT(ag_licence_begin(&lic, &h, &block, key), -AG_EPERM);
}

static void test_licence_key_file(void)
{
    uint8_t     key[32];
    const char *ok = "000102030405060708090a0b0c0d0e0f"
                     "101112131415161718191A1B1C1D1E1F\r\n";
    AG_CHECK(ag_licence_parse_key(ok, strlen(ok), key));
    AG_CHECK_INT(key[0x1f], 0x1f);
    AG_CHECK(!ag_licence_parse_key("00", 2, key));
    AG_CHECK(!ag_licence_parse_key(ok, 63, key));
    const char *bad = "zz0102030405060708090a0b0c0d0e0f"
                      "101112131415161718191a1b1c1d1e1f";
    AG_CHECK(!ag_licence_parse_key(bad, strlen(bad), key));

    uint8_t id[AG_LICENCE_ID_LEN];
    key_of(key, 0);
    ag_licence_key_id(key, id);
    AG_CHECK_INT(id[0], 0x00);
    AG_CHECK_INT(id[7], 0x37);

    /* No block in a file the shop did not make. */
    ag_licence_block_t block;
    AG_CHECK_INT(ag_licence_find(k_plain, sizeof(k_plain), &block), -AG_ENOENT);
}

void run_licence_tests(void)
{
    printf("licence\n");
    test_licence_reads_back();
    test_licence_refuses_another_key();
    test_licence_key_file();
}
