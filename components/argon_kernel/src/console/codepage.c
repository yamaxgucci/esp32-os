static const struct {
    uint16_t    number;
    const char *title;
} k_pages[AG_CP_COUNT] = {
    [AG_CP_437] = {437, "CP437 - PC, box drawing, no Cyrillic"},
    [AG_CP_866] = {866, "CP866 - MS-DOS Cyrillic"},
    [AG_CP_1251] = {1251, "CP1251 - Windows Cyrillic, no box drawing"},
};

/* CP437 is where a PC starts, and a system that boots in Cyrillic without being
 * asked would surprise everyone whose files are not. */
static ag_cp_t s_active = AG_CP_437;

static bool valid(ag_cp_t cp) { return cp >= 0 && cp < AG_CP_COUNT; }

uint32_t ag_cp_to_unicode(ag_cp_t cp, uint8_t byte)
{
    if (byte < 0x80u) {
        return byte;
    }
    if (!valid(cp)) {
        return 0;
    }
    return k_high[cp][byte - 0x80u];
}

int32_t ag_cp_from_unicode(ag_cp_t cp, uint32_t codepoint)
{
    if (codepoint < 0x80u) {
        return (int32_t)codepoint;
    }
    if (!valid(cp) || codepoint > 0xffffu) {
        return -1;
    }
    for (uint32_t i = 0; i < 128u; i++) {
        if (k_high[cp][i] == (uint16_t)codepoint) {
            return (int32_t)(0x80u + i);
        }
    }
    return -1;
}

size_t ag_utf8_encode(uint32_t codepoint, char out[4])
{
    if (out == NULL || codepoint > 0x10ffffu) {
        return 0;
    }
    if (codepoint < 0x80u) {
        out[0] = (char)codepoint;
        return 1;
    }
    if (codepoint < 0x800u) {
        out[0] = (char)(0xc0u | (codepoint >> 6));
        out[1] = (char)(0x80u | (codepoint & 0x3fu));
        return 2;
    }
    if (codepoint < 0x10000u) {
        out[0] = (char)(0xe0u | (codepoint >> 12));
        out[1] = (char)(0x80u | ((codepoint >> 6) & 0x3fu));
        out[2] = (char)(0x80u | (codepoint & 0x3fu));
        return 3;
    }
    out[0] = (char)(0xf0u | (codepoint >> 18));
    out[1] = (char)(0x80u | ((codepoint >> 12) & 0x3fu));
    out[2] = (char)(0x80u | ((codepoint >> 6) & 0x3fu));
    out[3] = (char)(0x80u | (codepoint & 0x3fu));
    return 4;
}

uint16_t ag_cp_number(ag_cp_t cp)
{
    return valid(cp) ? k_pages[cp].number : 0u;
}

bool ag_cp_from_number(uint16_t number, ag_cp_t *out)
{
    for (int i = 0; i < AG_CP_COUNT; i++) {
        if (k_pages[i].number == number) {
            if (out != NULL) {
                *out = (ag_cp_t)i;
            }
            return true;
        }
    }
    return false;
}

const char *ag_cp_title(ag_cp_t cp)
{
    return valid(cp) ? k_pages[cp].title : "unknown";
}

ag_cp_t ag_cp_active(void) { return s_active; }

void ag_cp_set_active(ag_cp_t cp)
{
    if (valid(cp)) {
        s_active = cp;
    }
}
