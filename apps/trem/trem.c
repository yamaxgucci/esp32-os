/*
 * TREM - a tremolo, and the first thing to go through the effect registry.
 *
 * It is here to answer one question: can a program use sound processing that
 * another program brought, found by name at run time, with neither of them
 * knowing about the other?  So it is deliberately the smallest effect worth
 * hearing - the level goes up and down, nothing else - because what is being
 * tested is the seam and not the sound.
 *
 *   drv install c:\TREM.SYS
 *   dev                      -> trem  fx  TREM
 *   run c:\STOMP.AXE jcm800 ... fx trem
 *
 * A .SYS rather than an .AXE because the registry only lets a driver publish
 * a device - `add() outside of ag_driver_init is refused`.  That rule is
 * right for the thing it was written about and is the first thing to revisit
 * when effects stop being an experiment: an effect is much more like an
 * application than like a driver, and it should not have to be installed to
 * be offered.
 *
 * SPDX-License-Identifier: Apache-2.0
 */
#include <argon/argon.h>
#include <string.h>

#include "ag_dsp.h"

AG_APP("TREM", "1.0", "argon", AG_AXE_DRIVER);

/*
 * The sine is a table of a quarter wave, read four ways, because a tremolo at
 * 5 Hz over a 64-frame block needs one value a block and a libm would be the
 * largest thing in this file by far.
 */
#define TABLE_N 64

static struct {
    uint32_t rate;
    uint8_t  channels;
    uint8_t  depth;   /* 0..100, how much of the level it takes away */
    uint32_t phase;   /* 0..0xffffffff over one cycle                */
    uint32_t step;    /* added a frame                               */
    int16_t  sine[TABLE_N];
} s;

static void build_sine(void)
{
    /* Two parabolas, which is a sine to within two per cent - and two per
     * cent of a tremolo's shape is not audible, while a table that has to be
     * generated by libm is a dependency this driver does not want. */
    int i;
    for (i = 0; i < TABLE_N; i++) {
        const int32_t x = (int32_t)i * 32767 / (TABLE_N - 1); /* 0..32767 */
        const int32_t y = x - (int32_t)(((int64_t)x * x) >> 15); /* 0..8192 */
        s.sine[i] = (int16_t)(y * 4);
    }
}

static uint32_t set_rate_hz(uint32_t hz_tenths)
{
    if (s.rate == 0u) {
        return 0u;
    }
    /* A full cycle is 2^32 of phase, so a step is 2^32 * f / rate. */
    const uint64_t full = 0x100000000ull;
    s.step = (uint32_t)((full * (uint64_t)hz_tenths) / (10ull * s.rate));
    return s.step;
}

static ag_err_t fx_prepare(ag_device_t *dev, uint32_t rate, uint32_t max_frames,
                           uint8_t channels)
{
    (void)dev;
    (void)max_frames; /* nothing is held per block, so the size is not needed */
    s.rate = (rate > 0u) ? rate : 22050u;
    s.channels = (channels > 0u) ? channels : 1u;
    (void)set_rate_hz(50u); /* 5.0 Hz, which reads as a tremolo and not a wobble */
    return AG_OK;
}

static ag_err_t fx_process(ag_device_t *dev, int16_t *buf, uint32_t frames)
{
    (void)dev;
    if (buf == NULL) {
        return -AG_EINVAL;
    }
    if (s.depth == 0u || s.step == 0u) {
        return AG_OK; /* at nothing, it is not in the way */
    }
    for (uint32_t i = 0; i < frames; i++) {
        /* The table is a quarter wave; the top two bits of the phase say
         * which quarter and therefore how to read it. */
        const uint32_t q = s.phase >> 30;
        const uint32_t t = (s.phase >> 24) & 0x3fu;
        const int32_t  v = (q == 0u || q == 2u) ? s.sine[t]
                                                : s.sine[TABLE_N - 1 - t];
        const int32_t  wave = (q < 2u) ? v : -v; /* -32767..32767 */
        /* 1.0 at the top of the wave, (1 - depth) at the bottom. */
        const int32_t  gain =
            32768 - (((32768 - wave) / 2) * (int32_t)s.depth) / 100;
        for (uint8_t c = 0; c < s.channels; c++) {
            const uint32_t at = i * s.channels + c;
            buf[at] = ag_sat16(((int32_t)buf[at] * gain) >> 15);
        }
        s.phase += s.step;
    }
    return AG_OK;
}

static void fx_reset(ag_device_t *dev)
{
    (void)dev;
    s.phase = 0u;
}

static ag_err_t fx_set_amount(ag_device_t *dev, uint8_t percent)
{
    (void)dev;
    s.depth = (percent > 100u) ? 100u : percent;
    return AG_OK;
}

static const char *fx_amount_name(ag_device_t *dev)
{
    (void)dev;
    return "DEPTH";
}

static const ag_fx_ops_t k_fx = {
    .size = sizeof(ag_fx_ops_t),
    .prepare = fx_prepare,
    .process = fx_process,
    .reset = fx_reset,
    .set_amount = fx_set_amount,
    .amount_name = fx_amount_name,
};

/* Nothing: an effect is not opened, read or written - it is called through
 * its class table.  The registry wants a table all the same. */
static const ag_dev_ops_t k_ops = { 0 };

ag_err_t ag_driver_init(void)
{
    memset(&s, 0, sizeof(s));
    build_sine();
    s.depth = 60u; /* audible without being a gimmick, until somebody turns it */
    s.channels = 1u;

    const ag_dev_add_t desc = {
        .name = "trem",
        .driver = "TREM",
        .cls = AG_DEV_FX,
        .flags = 0u,
        .ops = &k_ops,
        .class_ops = &k_fx,
        .priv = &s,
    };
    return ag_dev_add(&desc);
}
